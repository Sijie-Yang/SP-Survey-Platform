import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  asObjectSchema,
  buildArtifact,
  buildOperationSchemas,
} from './platform-schema-core.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(repoRoot, 'src/lib/platformSchema/registry.json');
const browserPath = resolve(repoRoot, 'src/lib/platformSchema/generated.js');
const workerPath = resolve(repoRoot, 'worker-lib/platformSchema.generated.mjs');
const check = process.argv.includes('--check');

const source = JSON.parse(await readFile(sourcePath, 'utf8'));

const artifact = buildArtifact(source);
const serialized = JSON.stringify(artifact);
const hash = `sha256:${createHash('sha256').update(serialized).digest('hex')}`;
const questionTypeIds = Object.keys(artifact.questionTypes);
const entitySchemas = Object.fromEntries(
  Object.entries(artifact.entities).map(([id, entity]) => [id, asObjectSchema(entity)]),
);
const { operationTypes, itemSchema, contractSchema } = buildOperationSchemas(artifact);

function moduleText(target) {
  const banner = `// AUTO-GENERATED by scripts/sync-platform-schema.mjs from src/lib/platformSchema/registry.json.\n// Do not edit by hand. Run npm run schema:sync.\n`;
  return `${banner}
export const PLATFORM_SCHEMA_HASH = ${JSON.stringify(hash)};
export const PLATFORM_SCHEMA = ${JSON.stringify(artifact, null, 2)};
export const QUESTION_TYPE_IDS = ${JSON.stringify(questionTypeIds, null, 2)};
export const OPERATION_TYPES = ${JSON.stringify(operationTypes, null, 2)};
export const ENTITY_SCHEMAS = ${JSON.stringify(entitySchemas, null, 2)};
export const SURVEY_CONFIG_SCHEMA = ENTITY_SCHEMAS.survey;
export const OPERATION_ITEM_SCHEMA = ${JSON.stringify(itemSchema, null, 2)};
export const OPERATION_CONTRACT_SCHEMA = ${JSON.stringify(contractSchema, null, 2)};
export const GENERATED_SCHEMA_TARGET = ${JSON.stringify(target)};
`;
}

const outputs = [
  [browserPath, moduleText('browser')],
  [workerPath, moduleText('worker')],
];

if (check) {
  const drift = [];
  for (const [path, expected] of outputs) {
    let actual = '';
    try {
      actual = await readFile(path, 'utf8');
    } catch {
      // Missing generated files are reported as drift.
    }
    if (actual !== expected) drift.push(path.slice(repoRoot.length + 1));
  }
  if (drift.length) {
    throw new Error(`Generated platform schema is stale: ${drift.join(', ')}. Run npm run schema:sync.`);
  }
  console.log(`Platform schema is synchronized (${hash}; ${questionTypeIds.length} question types; ${operationTypes.length} public operations).`);
} else {
  await Promise.all(outputs.map(([path, text]) => writeFile(path, text)));
  console.log(`Wrote ${outputs.length} platform schema artifacts (${hash}).`);
}
